import { describe, expect, test } from 'vitest'
import { readFileSync } from 'node:fs'
import { POOLS } from './plan-generator.js'
import { EXDB } from './exercises-data.js'
import names from '../exercise-names/pt-BR.js'
import descs from '../exercise-desc/pt-BR.js'
import steps from '../instr/pt-BR.js'
import EN_DESC from '../exercise-desc/en.js'
import EN_STEPS from '../instr/en.js'

// The exercises the generated plans use, and the ones with a video in docs/curadoria-videos.csv,
// must read in Brazilian Portuguese everywhere: name, short description and "Como fazer".
// The text lives in catalogue/i18n/pt-BR.json; nothing here is generated by hand.
const csv = readFileSync(new URL('../../../docs/curadoria-videos.csv', import.meta.url), 'utf8')
const csvIds = csv.split('\n').slice(1).map(l => /^"?(\d{4,5})"?,/.exec(l)?.[1]).filter(Boolean)
const planIds = [...new Set(Object.values(POOLS).flatMap(place => Object.values(place).flat()))]
const SCOPE = [...new Set([...planIds, ...csvIds])].sort()
// Everything curated, plan or not: whatever has a pt-BR description is held to the same rules.
const CURATED = Object.keys(descs).sort()
const EN_NAME = new Map(EXDB.map(e => [e.id, e.n]))

// English words that give an untranslated sentence away (none of them is Portuguese).
const ENGLISH = /(?:^|[^\p{L}])(?:the|your|with|from|and|you|towards?|repeat|desired|starting|slowly|hold|while|then|back|straight|ground|feet|hands|body|legs|arms|knees|shoulders|until|that|into)(?=$|[^\p{L}])/iu
// English equipment/movement words in a name. Loanwords the gyms use as they are (leg press, good
// morning, pull through, swing, kettlebell, goblet, burpee, Smith) are not on this list.
const ENGLISH_NAME = /(?:^|[^\p{L}])(?:barbell|dumbbells?|cable|lever|leverage|machine|with|and|the|raise|lunge|bridge|row|pulldown|crunch|deadlift|calf|thrust|glute|kick|bird|dog|dead|bug|bench|incline|decline|seated|standing|lying|band|push|up)(?=$|[^\p{L}])/iu
const PROPER = new Set(['Smith', 'PVC', 'EZ', 'TRX'])
// Names that are the established term in Brazil as they are (the app then shows no English twin).
const LOANWORD = new Set(['1160'])

describe('pt-BR text of the exercises used by the plans', () => {
  test('the scope is the 54 plan ids plus the video curation', () => {
    expect(planIds).toHaveLength(54)
    expect(csvIds.length).toBeGreaterThan(0)
    for (const id of SCOPE) expect(EN_NAME.has(id), id).toBe(true)
  })

  test('every id in scope has a name, a description and 4 to 7 steps in pt-BR', () => {
    for (const id of SCOPE) {
      expect(names[id], `${id} name`).toBeTruthy()
      expect(descs[id], `${id} description`).toBeTruthy()
      expect(steps[id], `${id} steps`).toBeTruthy()
      expect(steps[id].length, `${id} steps`).toBeGreaterThanOrEqual(4)
      expect(steps[id].length, `${id} steps`).toBeLessThanOrEqual(7)
    }
  })

  test('the English the E2E run found is gone', () => {
    expect(descs['1197']).not.toMatch(/bodyweight squat/i)
    expect(steps['1197'].join(' ')).not.toMatch(/shoulder-width/i)
  })

  describe.each(CURATED)('%s', id => {
    const name = names[id]
    const desc = descs[id]
    const list = steps[id]

    test('name is in sentence case, Portuguese and without an English suffix', () => {
      expect(name[0], name).toBe(name[0].toLocaleUpperCase('pt-BR'))
      const words = name.split(/\s+/).slice(1).map(w => w.replace(/[,.]$/, ''))
      for (const w of words) {
        if (/^\p{Lu}/u.test(w)) expect(PROPER.has(w), `${name}: "${w}" should be lower-case`).toBe(true)
      }
      expect(name, name).not.toMatch(ENGLISH_NAME)
      expect(name, name).not.toMatch(/[()]/)
      expect(name, name).not.toContain('—')
      if (!LOANWORD.has(id)) expect(name.toLocaleLowerCase('pt-BR'), name).not.toBe(EN_NAME.get(id).toLocaleLowerCase('en').replace(/ v\. \d$/, '')) // a name copied from English
    })

    test('description is 1 or 2 sentences of Portuguese', () => {
      expect(desc, id).not.toBe(EN_DESC[id])
      expect(desc, id).not.toMatch(ENGLISH)
      expect(desc, id).not.toContain('—')
      const sentences = desc.split(/(?<=[.!?])\s+/).filter(Boolean)
      expect(sentences.length, desc).toBeGreaterThanOrEqual(1)
      expect(sentences.length, desc).toBeLessThanOrEqual(2)
      expect(desc.endsWith('.'), desc).toBe(true)
    })

    test('steps are short Portuguese sentences, not the English ones', () => {
      list.forEach((step, i) => {
        expect(step, `${id} step ${i + 1}`).not.toBe(EN_STEPS[id]?.[i])
        expect(step, `${id} step ${i + 1}`).not.toMatch(ENGLISH)
        expect(step, `${id} step ${i + 1}`).not.toContain('—')
        expect(step[0], `${id} step ${i + 1}`).toBe(step[0].toLocaleUpperCase('pt-BR'))
        expect(step.endsWith('.'), `${id} step ${i + 1}`).toBe(true)
        expect(step.length, `${id} step ${i + 1} is too long`).toBeLessThanOrEqual(260)
      })
    })
  })

  test('uses Brazilian terms, not the Portugal ones', () => {
    const text = Object.entries(descs).flatMap(([id]) => [names[id], descs[id], ...steps[id]]).join('\n')
    expect(text).not.toMatch(/(?:^|[^\p{L}])(?:anca|abdómen|gémeos|ecrã|ginásio|omoplatas?|comboio|pega)(?=$|[^\p{L}])/iu)
  })
})
